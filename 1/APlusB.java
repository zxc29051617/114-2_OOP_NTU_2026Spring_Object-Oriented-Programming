/**
 * Provides an addition operation for two integers.
 */
public class APlusB {

    /**
     * Creates an addition helper.
     */
    public APlusB() {
    }

    /**
     * Adds two integers.
     *
     * @param A the first integer
     * @param B the second integer
     * @return the sum of {@code A} and {@code B}
     */
    public static int plus(int A, int B) {
        return A + B;
    }
}
